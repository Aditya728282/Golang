package main

import "fmt"

func main() {
	fmt.Println("Print two values: ")
	fmt.Println(10)
	fmt.Println(7)

	// Boolean values
	fmt.Println(true)

	// Float values

	fmt.Println(3.14)
	fmt.Println(2.7)
	// Arithmetic operations
	fmt.Println(4 + 7)
	fmt.Println(4.0 / 7.0)
	fmt.Println(4.0 * 7.0)
	fmt.Println(4.0 - 7.0)
	fmt.Println(4 % 7)
	fmt.Println(4 > 7)
	fmt.Println(4 < 7)
	fmt.Println(4 >= 7)
	fmt.Println(4 <= 7)
	fmt.Println(4 == 7)
	fmt.Println(4 != 7)

	// Mixing types
	fmt.Println(4 + 7.5)
	fmt.Println(4.0 + 7)

	//

}
