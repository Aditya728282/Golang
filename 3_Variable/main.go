package main

import "fmt"

func main() {

	// Variable declaration and initialization
	var name string = " Aditya Kumar"
	var age int = 21

	fmt.Println(name)
	fmt.Println((age))

	// short variable declaration
	city := "Gurgaon"
	fmt.Println(city)

	// Multiple variable declaration
	var country, continent string = "India", "Asia"
	fmt.Println(country, continent)

	// pre inint variable
	var num int
	num = 77
	fmt.Println(num)

	// float variable

	var num_1 float32
	// pi = 3.142
	num_1 = 77.14
	fmt.Println(num_1)
}
